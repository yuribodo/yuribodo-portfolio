/** Small initial terrain maps; full authored maps replace them after entry. */
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const sharp=createRequire(require.resolve('next/package.json'))('sharp');
const names=['soil-color','soil-normal','meadow-color','meadow-normal','rock-face-detail','rock-face-normal'];
const urls=[];
await fs.mkdir('public/lobby/baked',{recursive:true});
for(const name of names){
 const bytes=await sharp(`public/lobby/world/${name}.webp`).resize({width:256,height:256,fit:'inside'}).webp({quality:95,effort:6}).toBuffer();
 const hash=createHash('sha256').update(bytes).digest('hex').slice(0,16),url=`/lobby/baked/${name}-${hash}.webp`;
 await fs.writeFile(`public${url}`,bytes);urls.push(url);
}
await fs.writeFile('lib/lobby/ground-preview-manifest.ts',`// Generated by scripts/bake-ground-preview.mjs.\nexport const GROUND_PREVIEW_TEXTURES = ${JSON.stringify(urls,null,2)};\n`);
